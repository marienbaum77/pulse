def main(seed: int = 7, hard: bool = False) -> None:
    rnd = random.Random(seed)
    names = list(SOURCES)
    rows = []
    events = EVENTS + (HARD_EVENTS if hard else [])
    for ei, ev in enumerate(events):
        base = 44 - ei * (4 if hard else 6)  # событие «стартует» в разное время; в трудном наборе события накладываются по времени
        for k in range(rnd.randint(5, 6) if hard else rnd.randint(6, 7)):
            src = names[(ei + k) % len(names)]
            picked = sorted(rnd.sample(range(len(ev["facts"])), rnd.randint(2, 3) if hard else rnd.randint(3, 4)))
            rows.append(
                dict(
                    title=ev["titles"][k % len(ev["titles"])],
                    text=" ".join(ev["facts"][i] for i in picked),
                    source=src,
                    authority=SOURCES[src],
                    hours_ago=round(max(base - k * rnd.uniform(0.8, 2.2), 0.5), 1),
                    gold=ev["id"],
                )
            )
    for ni, (title, text) in enumerate(NOISE + (HARD_NOISE if hard else [])):
        src = names[ni % len(names)]
        rows.append(dict(title=title, text=text, source=src, authority=SOURCES[src], hours_ago=round(rnd.uniform(2, 40), 1), gold=f"noise-{ni}"))
    rnd.shuffle(rows)
    for r in rows:
        print(json.dumps(r, ensure_ascii=False))


